package com.highlight.entity;

/**
 * Category of a character observation. The first group applies to {@link ObservationKind#APPEARANCE},
 * the second to {@link ObservationKind#CLOTHING}, the third to {@link ObservationKind#ROLE}.
 */
public enum ObservationCategory {
	HAIR,
	EYES,
	FACE,
	SKIN,
	BUILD,
	HEIGHT,
	AGE,
	MARKS,
	OTHER,
	OUTFIT,
	TOP,
	BOTTOM,
	OUTERWEAR,
	FOOTWEAR,
	HEADWEAR,
	ACCESSORY,
	OCCUPATION,
	SOCIAL_CLASS
}
